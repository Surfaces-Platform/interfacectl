async function writeJsonAtomic(filePath: string, payload: unknown): Promise<void> {
  await mkdir(path.dirname(filePath), { recursive: true });
  const tempPath = `${filePath}.tmp`;
  await writeFile(tempPath, `${stableStringify(payload)}\n`, "utf-8");
  await rename(tempPath, filePath);
}

async function readJson<T>(filePath: string, fallback: T): Promise<T> {
  if (!existsSync(filePath)) return fallback;
  try {
    const raw = await readFile(filePath, "utf-8");
    return JSON.parse(raw) as T;
  } catch {
    return fallback;
  }
}

function sha256FromContent(content: string): string {
  return createHash("sha256").update(content).digest("hex");
}

function toRelative(root: string, candidate: string): string {
  return path.relative(root, candidate);
}

const EXPLICIT_URL_SCHEME_PATTERN = /^[a-z][a-z\d+\-.]*:\/\//i;

function stripPort(candidate: string): string {
  if (candidate.startsWith("[")) {
    const closingBracket = candidate.indexOf("]");
    if (closingBracket >= 0) {
      return candidate.slice(1, closingBracket);
    }
  }
  return candidate.replace(/:\d+$/, "");
}

function hostnameFromUrlInput(rawInput: string): string {
  const withoutProtocolRelativePrefix = rawInput.replace(/^\/\//, "");
  const authority = withoutProtocolRelativePrefix.split(/[/?#]/, 1)[0] ?? "";
  return stripPort(authority).toLowerCase();
}

function isLocalHostname(hostname: string): boolean {
  if (!hostname) {
    return false;
  }
  if (hostname === "localhost" || hostname === "::1" || hostname === "0.0.0.0") {
    return true;
  }
  if (/^\d{1,3}(?:\.\d{1,3}){3}$/.test(hostname)) {
    return hostname.startsWith("127.") ||
      hostname.startsWith("10.") ||
      hostname.startsWith("192.168.") ||
      /^172\.(1[6-9]|2\d|3[0-1])\./.test(hostname);
  }
  return hostname.endsWith(".local");
}

export function normalizeRemoteUrlInput(rawInput: string): string {
  const trimmed = rawInput.trim();
  if (trimmed.length === 0) {
    return new URL(trimmed).toString();
  }
  if (EXPLICIT_URL_SCHEME_PATTERN.test(trimmed)) {
    return new URL(trimmed).toString();
  }

  const hostname = hostnameFromUrlInput(trimmed);
  const scheme = isLocalHostname(hostname) ? "http://" : "https://";
  const candidate = trimmed.replace(/^\/\//, "");
  return new URL(`${scheme}${candidate}`).toString();
}
export function suggestSurfaceIdFromUrl(rawUrl: string): string {
  const url = new URL(normalizeRemoteUrlInput(rawUrl));
  const host = url.hostname.replace(/^www\./, "");
  const pathToken = url.pathname
    .split("/")
    .map((token) => token.trim())
    .filter(Boolean)[0];
  const candidate = [host.replace(/\./g, "-"), pathToken]
    .filter(Boolean)
    .join("-");
  const normalized = candidate
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
  return normalized.length > 0 ? normalized : "surface";
}

export function suggestSurfaceName(surfaceId: string): string {
  return surfaceId
    .split("-")
    .filter(Boolean)
    .map((token) => token.charAt(0).toUpperCase() + token.slice(1))
    .join(" ");
}

export function suggestSurfaceIdFromPath(rawPath: string): string {
  const candidate = path.basename(rawPath);
  const normalized = candidate
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
  return normalized.length > 0 ? normalized : "surface";
}

export function buildBootstrapContract(input: {
  surfaceId: string;
  surfaceName: string;
  sourceUrl: string;
  authAware: boolean;
}): Record<string, unknown> {
  const url = new URL(input.sourceUrl);
  return {
    $schema:
      "https://contracts.surfaces.local/web.surface.contract.schema.json",
    contractId: `${input.surfaceId}.generated`,
    version: "0.1.0",
    description: "Generated by interfacectl init onboarding bootstrap.",
    surfaces: [
      {
        id: input.surfaceId,
        displayName: input.surfaceName,
        type: "web",
        domain: url.origin,
        requiredSections: ["extracted.placeholder"],
        allowedFonts: ["sans-serif"],
        layout: { maxContentWidth: 1120 },
      },
    ],
    sections: [
      {
        id: "extracted.placeholder",
        intent: "extracted",
        description: "Placeholder; sections are not inferred during URL onboarding bootstrap.",
      },
    ],
    constraints: {
      motion: {
        allowedDurationsMs: [120],
        allowedTimingFunctions: ["linear"],
      },
    },
    color: {
      policy: "warn",
      allowedValues: [],
    },
    x_extracted: {
      routes: [url.pathname || "/"],
      hasShell: false,
      designSystemComponents: [],
      authAware: input.authAware,
    },
    x_onboarding: {
      sourceUrl: input.sourceUrl,
      mode: "bootstrap",
    },
  };
}

export async function writeBootstrapArtifacts(input: {
  rootDir: string;
  outDir?: string;
  surfaceId: string;
  contract: Record<string, unknown>;
  report: BootstrapExtractionReport;
}): Promise<{
  contractPath: string;
  reportPath: string;
}> {
  const generatedDir = input.outDir
    ? path.resolve(input.rootDir, input.outDir)
    : path.resolve(input.rootDir, "contracts", "generated");
  const contractPath = path.join(generatedDir, `${input.surfaceId}.contract.json`);
  const reportPath = path.join(generatedDir, `${input.surfaceId}.extraction.json`);
  await writeJsonAtomic(contractPath, input.contract);
  await writeJsonAtomic(reportPath, input.report);
  return { contractPath, reportPath };
}

export async function emitOnboardingRunArtifact(input: {
  rootDir: string;
  surfaceId: string;
  source: OnboardingRunSource;
  status: ValidationOutcome;
  findingCodes: string[];
  extractionPath: string;
  reportPath: string;
}): Promise<{ runId: string }> {
  const result = emitContractRunArtifact({
    rootDir: input.rootDir,
    surfaceId: input.surfaceId,
    source: input.source,
    status: input.status,
    findingCodes: input.findingCodes,
    extractionPath: input.extractionPath,
    reportPath: input.reportPath,
  });
  return { runId: result.runId };
}

export async function emitBootstrapRunArtifact(input: {
  rootDir: string;
  surfaceId: string;
  status: ValidationOutcome;
  findingCodes: string[];
  extractionPath: string;
  reportPath: string;
}): Promise<{ runId: string }> {
  return emitOnboardingRunArtifact({
    ...input,
    source: "bootstrap",
  });
}
